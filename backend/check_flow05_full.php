<?php
require __DIR__.'/vendor/autoload.php';
$app = require __DIR__.'/bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();
use App\Models\User;
use App\Models\MeetingRequest;
use App\Models\MeetingScheduleProposal;
use App\Models\OrganizationalUnit;
use App\Models\Employee;
use App\Actions\MeetingRequests\SubmitMultiHighAuthorityRequest;
use App\Actions\MeetingRequests\ApproveMultiHighRequesterSide;
use App\Actions\MeetingRequests\StartMultiHighUnitReview;
use App\Actions\MeetingRequests\ApproveMultiHighParticipatingUnit;
use App\Actions\MeetingRequests\SubmitMultiHighRequestToAuthorityOffice;
use App\Actions\MeetingRequests\StartMultiHighAuthorityOfficeReview;
use App\Actions\MeetingRequests\ForwardMultiHighToHighAuthority;
use App\Actions\MeetingRequests\ApproveMultiHighByAuthority;
use App\Actions\MeetingRequests\StartMultiHighAuthorityScheduling;
use App\Actions\MeetingRequests\ProposeMultiHighAuthoritySchedule;
use App\Actions\MeetingRequests\AcknowledgeMultiHighAuthoritySchedule;
use App\Actions\MeetingRequests\ConfirmMultiHighAuthoritySchedule;
use App\Actions\MeetingRequests\ManageMultiHighUnitParticipants;
use App\Actions\MeetingRequests\ConfirmMultiHighUnitParticipants;
use App\Actions\MeetingRequests\ManageMultiHighAuthorityParticipants;
use App\Actions\MeetingRequests\ConfirmMultiHighAuthorityParticipants;
use App\Actions\MeetingRequests\ConvertMultiHighAuthorityRequestToMeeting;

$u = fn(string $e) => User::where('email',$e)->firstOrFail();
$unit = fn(string $c) => OrganizationalUnit::where('code',$c)->firstOrFail();
$emp = fn(string $n) => Employee::where('employee_number',$n)->firstOrFail();
$req = MeetingRequest::where('flow_type','MULTI_DIRECTORATE_WITH_HIGH_AUTHORITY')->latest('id')->firstOrFail();
$techExec=$u('tech.exec@example.test'); $techDirector=$u('tech.director@example.test'); $financeExec=$u('finance.exec@example.test'); $financeDirector=$u('finance.director@example.test'); $office=$u('authority.office@example.test'); $authority=$u('high.authority@example.test'); $secretary=$u('executive.secretary@example.test');
$tech=$unit('TECH'); $finance=$unit('FIN'); $techEmployee=$emp('EMP-TECH-003'); $financeEmployee=$emp('EMP-FIN-002'); $authorityEmployee=$emp('EMP-AUTH-001');
app(SubmitMultiHighAuthorityRequest::class)($techExec,$req);
app(ApproveMultiHighRequesterSide::class)($techDirector,$req);
app(StartMultiHighUnitReview::class)($financeExec,$req,$finance->id);
app(ApproveMultiHighParticipatingUnit::class)($financeDirector,$req,$finance->id);
app(SubmitMultiHighRequestToAuthorityOffice::class)($techExec,$req);
app(StartMultiHighAuthorityOfficeReview::class)($office,$req);
app(ForwardMultiHighToHighAuthority::class)($office,$req);
app(ApproveMultiHighByAuthority::class)($authority,$req,'تأیید آزمایشی مقام عالی');
app(StartMultiHighAuthorityScheduling::class)($secretary,$req);
app(ProposeMultiHighAuthoritySchedule::class)($secretary,$req,['meeting_date'=>now()->addWeek()->format('Y-m-d'),'start_time'=>'10:00','end_time'=>'11:00','location'=>'دفتر مقام','comment'=>'پیشنهاد رسمی آزمایشی']);
$proposal=MeetingScheduleProposal::where('meeting_request_id',$req->id)->latest('id')->firstOrFail();
app(AcknowledgeMultiHighAuthoritySchedule::class)($techExec,$req,$proposal,$tech->id);
app(AcknowledgeMultiHighAuthoritySchedule::class)($financeExec,$req,$proposal,$finance->id);
app(ConfirmMultiHighAuthoritySchedule::class)($secretary,$req);
app(ManageMultiHighUnitParticipants::class)($techExec,$req,$tech->id,[$techEmployee->id]);
app(ConfirmMultiHighUnitParticipants::class)($techExec,$req,$tech->id);
app(ManageMultiHighUnitParticipants::class)($financeExec,$req,$finance->id,[$financeEmployee->id]);
app(ConfirmMultiHighUnitParticipants::class)($financeExec,$req,$finance->id);
app(ManageMultiHighAuthorityParticipants::class)($office,$req,[$authorityEmployee->id]);
app(ConfirmMultiHighAuthorityParticipants::class)($office,$req);
$meeting=app(ConvertMultiHighAuthorityRequestToMeeting::class)($secretary,$req,['agenda'=>'آجندای جلسهٔ چندریاستی با مقام عالی']);
echo json_encode(['request_id'=>$req->id,'status'=>$req->fresh()->status,'meeting_id'=>$meeting->id,'meeting_units'=>$meeting->units()->count(),'participants'=>$meeting->participants()->count(),'authority_context'=>$meeting->authorityContext()->count(),'chairperson'=>$meeting->chairperson?->employee_number], JSON_UNESCAPED_UNICODE).PHP_EOL;
